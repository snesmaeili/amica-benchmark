"""Cross-recording replication of the implementation comparison.

The cost table rests on one recording, which is its weakest point: it cannot
distinguish a property of an implementation from a property of that fixture.
This runs the same protocol and the same implementations on all three
recordings and reports the two quantities that turned out to behave differently
-- agreement with the reference decomposition, and peak device memory.

The recordings are ordered by the data-adequacy factor
``k = frames / components^2`` because agreement tracks it. pAMICA's own
documentation puts the threshold where cross-backend agreement plateaus at
k ~ 60, and ds004621 is the only recording here below it; every implementation
loses agreement there, the Fortran reference included. Reporting agreement
without the recording it came from would misrepresent all of them.

Run from figures/src/:  python make_tab_cross_recording.py
"""
from __future__ import annotations

import json
from pathlib import Path

from _paths import DATA_ROOT as _WS, out

DEST = out("tab_cross_recording.tex")

# ds004505 comes from the main cost-table campaign; the other two from the
# replication run. Ordered by k, descending.
RECORDINGS = [
    ("ds004504", "Eyes-closed rest", "sub-37",
     _WS / "results/cross_recording/ds004504/cpu",
     _WS / "results/cross_recording/ds004504/gpu"),
    ("ds004505", "Table tennis", "sub-01",
     _WS / "results/mem_compare/cpu/ds004505_sub-01_mem",
     _WS / "results/rt_gpu_100"),
    ("ds004621", "Eyes-open rest", "sub-01",
     _WS / "results/cross_recording/ds004621/cpu",
     _WS / "results/cross_recording/ds004621/gpu"),
]

DISPLAY = {
    "amica_python_jax_chunked": r"\texttt{amica} (JAX, chunked)",
    "scott_huberty_torch": r"AMICA-Python (PyTorch)",
    "pyamica_torch": r"\texttt{pyamica} (PyTorch)",
    "pamica_torch": r"\texttt{pAMICA} (PyTorch)",
    "fortran_amica17": r"Fortran AMICA~1.7",
}
ORDER = ["amica_python_jax_chunked", "scott_huberty_torch", "pyamica_torch",
         "pamica_torch", "fortran_amica17"]
REFERENCE = "amica_python_jax"


def matched_min_r(reference, candidate) -> float | None:
    """Worst unsigned row correlation after Hungarian matching.

    Same definition as the fixed-workload audit, deliberately identical so the
    two tables cannot report different numbers for the same quantity.
    """
    import numpy as np
    from scipy.optimize import linear_sum_assignment

    a = np.asarray(reference, dtype=float)
    b = np.asarray(candidate, dtype=float)
    if a.shape != b.shape:
        return None
    a = a / np.linalg.norm(a, axis=1, keepdims=True)
    b = b / np.linalg.norm(b, axis=1, keepdims=True)
    c = np.abs(a @ b.T)
    row, col = linear_sum_assignment(-c)
    return float(np.min(c[row, col]))


def load(d: Path) -> dict[str, dict]:
    recs = {}
    for p in sorted(d.glob("*_result.json")):
        r = json.loads(p.read_text(encoding="utf-8"))
        if "error" not in r:
            recs[r["implementation"]] = r
    return recs


def main() -> None:
    cols = []
    for name, label, subject, cpu_dir, gpu_dir in RECORDINGS:
        cpu, gpu = load(cpu_dir), load(gpu_dir)
        ref = cpu.get(REFERENCE)
        if ref is None:
            print(f"  {name}: no {REFERENCE} reference, skipped")
            continue
        k = float(ref["n_samples"]) / float(ref["n_components"]) ** 2
        agree = {impl: matched_min_r(ref["W"], r["W"])
                 for impl, r in cpu.items() if "W" in r}
        vram = {impl: r.get("peak_vram_gb") for impl, r in gpu.items()}
        cols.append({"name": name, "label": label, "subject": subject, "k": k,
                     "n_components": int(ref["n_components"]),
                     "n_samples": int(ref["n_samples"]),
                     "agree": agree, "vram": vram})

    if not cols:
        raise SystemExit("no recordings resolved; nothing to write")

    o: list[str] = []
    add = o.append
    add(r"% Generated by figures/src/make_tab_cross_recording.py -- do not hand-edit.")
    add(r"\begin{table}[htbp]")
    add(r"\centering")
    add(r"\caption{")
    add(r"\textbf{The implementation comparison repeated on all three recordings.}")
    add(r"One run per implementation per recording, same protocol as")
    add(r"Table~\ref{tab:cross-implementation} (100 iterations, matched mixture")
    add(r"count, learning rate and Newton setting; each package at its own")
    add(r"algorithm constants). Agreement is the worst Hungarian-matched,")
    add(r"sign-aligned unmixing-row correlation against the \texttt{amica} JAX-CPU")
    add(r"run on the same recording. Recordings are ordered by the data-adequacy")
    add(r"factor \(k=T/C^{2}\), for \(T\) samples and \(C\) retained components.")
    add(r"\textbf{Agreement tracks \(k\) rather than the implementation}: every")
    add(r"estimator, the Fortran reference included, loses agreement on the")
    add(r"least-determined recording, so a single agreement figure quoted without")
    add(r"its recording would misrepresent all of them. Peak device memory, by")
    add(r"contrast, is stable in its ordering across all three. These are single")
    add(r"runs on one participant per recording and are descriptive.")
    add(r"}")
    add(r"\label{tab:cross-recording}")
    add(r"\footnotesize")
    add(r"\setlength{\tabcolsep}{4pt}")
    add(r"\begin{tabular}{l" + "c" * len(cols) + "}")
    add(r"\toprule")
    add("Recording & " + " & ".join(rf"\shortstack{{{c['label']}\\{c['name']}}}"
                                    for c in cols) + r" \\")
    add("Retained components & " + " & ".join(f"${c['n_components']}$" for c in cols) + r" \\")
    add(r"\(k=T/C^{2}\) & " + " & ".join(f"${c['k']:.0f}$" for c in cols) + r" \\")

    add(r"\midrule")
    # Brace counts differ between the halves: the f-string half doubles them,
    # the raw half does not. Closing \emph{ and the \multicolumn cell needs two.
    add(rf"\multicolumn{{{len(cols) + 1}}}{{l}}{{\emph{{Worst matched unmixing-row "
        r"correlation vs \texttt{amica} JAX-CPU}}\\")
    add(r"\addlinespace[1pt]")
    for impl in ORDER:
        cells = []
        for c in cols:
            v = c["agree"].get(impl)
            cells.append(f"${v:.4f}$" if v is not None else "--")
        add(f"{DISPLAY[impl]} & " + " & ".join(cells) + r" \\")

    add(r"\midrule")
    add(rf"\multicolumn{{{len(cols) + 1}}}{{l}}{{\emph{{Peak device memory (GiB), "
        r"one H100}}\\")
    add(r"\addlinespace[1pt]")
    for impl in ORDER:
        if impl == "fortran_amica17":
            continue  # CPU-only
        cells = []
        for c in cols:
            v = c["vram"].get(impl)
            cells.append(f"${v:.3f}$" if v is not None else "--")
        add(f"{DISPLAY[impl]} & " + " & ".join(cells) + r" \\")

    add(r"\bottomrule")
    add(r"\end{tabular}")
    add(r"\end{table}")

    DEST.write_text("\n".join(o) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {DEST}")
    for c in cols:
        pam = c["agree"].get("pamica_torch")
        vr = c["vram"].get("pamica_torch")
        print(f"  {c['name']}  C={c['n_components']:3d}  T={c['n_samples']:7d}  "
              f"k={c['k']:7.1f}  pAMICA |r|={pam:.4f}  VRAM={vr:.3f}")


if __name__ == "__main__":
    main()
