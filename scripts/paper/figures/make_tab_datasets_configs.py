#!/usr/bin/env python3
"""Generate tab_datasets_configs.tex from the run manifests.

Writing this generator surfaced an error in the published table. The caption
reads "Durations and data-sufficiency ratios are medians [IQR]", and the
durations are indeed median [IQR] -- they reproduce exactly. But the six
kappa values are median [**min, max**], not [IQR]:

    kappa_channels, Table tennis : published [54.5, 94.8]
                                   true IQR  [73.4, 79.6]
                                   min/max   [54.5, 94.8]  <- what is printed

The same holds for all six kappa columns across all three cohorts. The numbers
are not wrong; the bracket label is. This script emits the range explicitly and
labels it as a range, so the caption and the contents agree.

Per-subject values are deduplicated by subject id, because each subject appears
once per estimator/backend in the manifest set and kappa is a property of the
data, not of the estimator.

Usage:
    python make_tab_datasets_configs.py            # print to stdout
    python make_tab_datasets_configs.py --write    # write ../../tab_datasets_configs.tex
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import statistics as st
from pathlib import Path

from _paths import DATA_ROOT as WORKSPACE, out

HERE = Path(__file__).resolve().parent
OUT = out("tab_datasets_configs.tex")

# Editorial columns (not derivable from the manifests) alongside the manifest
# directory each cohort's numbers come from.
COHORTS = [
    {
        "label": "Table tennis", "accession": "ds004505",
        "role": "Active high-density stress test",
        "chans": "120 selected $\\rightarrow 64$ PCs\n(270--340 stored)",
        "sampling": "250~Hz native",
        "results_dir": "results/backend_parity_v3",
    },
    {
        "label": "Eyes-closed rest", "accession": "ds004504",
        "role": "Low-density resting replication",
        "chans": "19 $\\rightarrow 15$ PCs",
        "sampling": "500 $\\rightarrow$ 250~Hz",
        "results_dir": "results/ds004504_v3_50hz",
    },
    {
        "label": "Eyes-open rest", "accession": "ds004621",
        "role": "High-density resting replication",
        "chans": "127 stored $\\rightarrow 64$ PCs\n(128-channel system)",
        "sampling": "1000 $\\rightarrow$ 250~Hz",
        "results_dir": "results/ds004621_v3_50hz",
    },
]


def per_subject(results_dir: Path, accession: str) -> dict[str, dict]:
    found: dict[str, dict] = {}
    for f in glob.glob(str(results_dir / "*.json")):
        try:
            j = json.load(open(f, encoding="utf-8"))
        except Exception:
            continue
        if not isinstance(j, dict):
            continue
        d = j.get("_data") or {}
        if d.get("dataset") == accession and d.get("subject"):
            found[d["subject"]] = d
    return found


def med_iqr(vals: list[float]) -> tuple[float, float, float]:
    q = st.quantiles(sorted(vals), n=4, method="inclusive")
    return st.median(vals), q[0], q[2]


def med_range(vals: list[float]) -> tuple[float, float, float]:
    return st.median(vals), min(vals), max(vals)


def fmt(v: float, dp: int) -> str:
    # No thousands separator: the published table prints 1130.1, not 1,130.1.
    return f"{v:.{dp}f}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--workspace", default=str(WORKSPACE))
    args = ap.parse_args()
    ws = Path(args.workspace)

    rows, notes = [], []
    for c in COHORTS:
        subs = per_subject(ws / c["results_dir"], c["accession"])
        if not subs:
            raise SystemExit(f"no manifests for {c['accession']} in {c['results_dir']}")
        dur = [v["duration_s"] / 60 for v in subs.values() if v.get("duration_s")]
        kch = [v["kappa_channels"] for v in subs.values() if v.get("kappa_channels")]
        kef = [v["kappa_effective"] for v in subs.values() if v.get("kappa_effective")]

        dm, dq1, dq3 = med_iqr(dur)          # duration: genuinely median [IQR]
        cm, clo, chi = med_range(kch)        # kappa: median [min, max]
        em, elo, ehi = med_range(kef)

        rows.append(
            f"\\textbf{{{c['label']}}} &\n{c['accession']} &\n{c['role']} &\n"
            f"{len(subs)} &\n{c['chans']} &\n{c['sampling']};\n"
            f"{fmt(dm,1)} [{fmt(dq1,1)}, {fmt(dq3,1)}] min &\n"
            f"{fmt(cm,1)} ({fmt(clo,1)}--{fmt(chi,1)}) &\n"
            f"{fmt(em,1)} ({fmt(elo,1)}--{fmt(ehi,1)}) \\\\"
        )
        notes.append(f"{c['accession']}: n={len(subs)}")

    body = "\n\n".join(rows)
    tex = f"""% GENERATED by figures/src/make_tab_datasets_configs.py -- do not edit by hand.
\\begin{{table}}[htbp]
\\centering
\\caption{{
\\textbf{{Real-EEG datasets and single-model benchmark configurations.}}
Durations are medians [IQR]; data-sufficiency ratios are medians (range).
}}
\\label{{tab:datasets-configs}}

\\scriptsize
\\setlength{{\\tabcolsep}}{{2pt}}
\\renewcommand{{\\arraystretch}}{{1.08}}

\\begin{{tabular}}{{
    >{{\\raggedright\\arraybackslash}}p{{1.7cm}}
    >{{\\raggedright\\arraybackslash}}p{{1.15cm}}
    >{{\\raggedright\\arraybackslash}}p{{2.1cm}}
    c
    >{{\\raggedright\\arraybackslash}}p{{2.55cm}}
    >{{\\raggedright\\arraybackslash}}p{{2.45cm}}
    >{{\\raggedright\\arraybackslash}}p{{2.1cm}}
    >{{\\raggedright\\arraybackslash}}p{{2.1cm}}
}}
\\toprule
Cohort &
OpenNeuro &
Benchmark role &
$n$ &
Channels $\\rightarrow$ PCs &
Sampling; duration &
$\\kappa_{{\\mathrm{{channels}}}}$ &
$\\kappa_{{\\mathrm{{eff}}}}$ \\\\
\\midrule

{body}

\\bottomrule
\\end{{tabular}}

\\vspace{{3pt}}
\\begin{{minipage}}{{\\linewidth}}
\\scriptsize
\\textit{{Notes.}}
\\(\\kappa_{{\\mathrm{{channels}}}}=T/C^2\\) uses the analysed channel count,
whereas \\(\\kappa_{{\\mathrm{{eff}}}}=T/N^2\\) uses the retained PCA rank.
Ratios are reported as median with the full across-participant range in
parentheses, so the least favourable participant is visible.
All cohorts used raw OpenNeuro data, 1--100~Hz filtering, 250-Hz sampling,
matched within-participant inputs, and no manual component rejection.
Single-model \\texttt{{amica}} used \\(M=1\\), \\(K=3\\), seed~42, and a
3,000-iteration cap. Comparators used method-specific stopping with a
5,000-iteration maximum.
\\end{{minipage}}
\\end{{table}}
"""
    if args.write:
        OUT.write_text(tex, encoding="utf-8")
        print(f"wrote {OUT}")
    else:
        print(tex)
    print("cohorts: " + "; ".join(notes))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
