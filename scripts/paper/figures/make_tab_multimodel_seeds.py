"""YOR28: per-seed table for the synthetic multi-model controls.

The published version of this analysis rested on one seed. This table reports
all ten, including the seed in which recovery at the true model order failed --
which is the point of running more than one.

Run from figures/src/:  python make_tab_multimodel_seeds.py
"""
from __future__ import annotations

import json
import statistics as st
from pathlib import Path

from _paths import DATA_ROOT as _WS, out

_HERE = Path(__file__).resolve().parent
DEST = out("tab_multimodel_seeds.tex")

PUBLISHED = _WS / "figdata/multimodel_synthetic_2000/synthetic_summary.json"
SEEDS_DIR = _WS / "results/multimodel_seeds"


# The table states "N of M seeds" in its own footnote, so a silently short run
# does not look broken -- it looks like a different result. With seed 0 absent
# this printed "8 of 9 seeds" instead of "9 of 10" and exited 0. Declare the
# expected set and refuse to emit a table that does not cover it.
EXPECTED_SEEDS = frozenset(range(10))


def load_runs() -> dict[int, dict]:
    runs: dict[int, dict] = {}
    if PUBLISHED.exists():
        runs[0] = json.loads(PUBLISHED.read_text(encoding="utf-8"))
    for p in sorted(SEEDS_DIR.glob("seed*/synthetic_summary.json")):
        runs[int(p.parent.name.removeprefix("seed"))] = json.loads(
            p.read_text(encoding="utf-8"))

    missing = sorted(EXPECTED_SEEDS - runs.keys())
    if missing:
        raise SystemExit(
            f"refusing to write {DEST.name}: seeds {missing} are missing.\n"
            f"  seed 0 comes from {PUBLISHED}\n"
            f"  seeds 1-9 come from {SEEDS_DIR}/seedNN/synthetic_summary.json\n"
            "Set AMICA_BENCH_DATA to a tree that has them if this repository "
            "does not."
        )
    return runs


def sci(value: float, digits: int = 2) -> str:
    """LaTeX scientific notation. Built properly rather than by string surgery
    on an already-formatted number, which is how the exponent brace goes
    missing."""
    mantissa, exponent = f"{value:.{digits}e}".split("e")
    return rf"{mantissa}{{\times}}10^{{{int(exponent)}}}"


def by_h(run: dict, cond: str) -> dict[int, dict]:
    return {int(r["H"]): r for r in run[cond]}


def dll(run: dict, cond: str, H: int) -> float:
    d = by_h(run, cond)
    return d[H]["ll"] - d[1]["ll"]


def main() -> None:
    runs = load_runs()
    rows = []
    for s in sorted(runs):
        r = runs[s]
        ns3, ns10 = dll(r, "non_stationary", 3), dll(r, "non_stationary", 10)
        st3 = dll(r, "stationary", 3)
        rec = by_h(r, "non_stationary")[3]
        rows.append(dict(
            seed=s, dll3=ns3, frac=ns3 / ns10, sir=rec["sir_db"],
            err=rec["model_error"], neff=rec["n_eff"],
            stat3=st3, ratio=ns3 / max(st3, 1e-12),
        ))

    med = {k: st.median([r[k] for r in rows]) for k in
           ("dll3", "sir", "err", "neff", "stat3", "ratio")}
    n_ok = sum(1 for r in rows if r["frac"] > 0.95 and r["err"] < 1e-2)

    out: list[str] = []
    add = out.append
    add(r"% Generated by figures/src/make_tab_multimodel_seeds.py -- do not hand-edit.")
    add(r"\begin{table}[htbp]")
    add(r"\centering")
    add(r"\caption{")
    add(r"\textbf{Synthetic multi-model controls across ten seeds.} For each")
    add(r"seed, the in-sample likelihood gain at the true model order")
    add(r"\(M=3\) relative to \(M=1\), the fraction of the gain available at")
    add(r"\(M=10\) that \(M=3\) already captures, the regime-wise")
    add(r"signal-to-interference ratio, the matched map error, the effective")
    add(r"model count, and the corresponding gain for the matched stationary")
    add(r"recording. Seed~0 is the originally reported run. Recovery at the")
    add(r"generating order is typical but not guaranteed: in one seed the")
    add(r"\(M=3\) fit did not separate the three regimes, which a single-seed")
    add(r"evaluation could not have revealed. The separation from the")
    add(r"stationary control, by contrast, holds in every seed.")
    add(r"}")
    add(r"\label{tab:multimodel-seeds}")
    add(r"\footnotesize")
    add(r"\setlength{\tabcolsep}{4.5pt}")
    add(r"\begin{tabular}{ccccccc}")
    add(r"\toprule")
    add(r"Seed & \shortstack{$\Delta LL(3)$\\non-stationary} & "
        r"\shortstack{Fraction of\\$\Delta LL(10)$} & "
        r"\shortstack{SIR\\(dB)} & \shortstack{Matched\\map error} & "
        r"$N_{\mathrm{eff}}$ & \shortstack{$\Delta LL(3)$\\stationary} \\")
    add(r"\midrule")
    for r in rows:
        flag = "" if (r["frac"] > 0.95 and r["err"] < 1e-2) else r"$^{*}$"
        add(f"{r['seed']}{flag} & ${r['dll3']:.4f}$ & ${r['frac']:.3f}$ & "
            f"${r['sir']:.1f}$ & ${sci(r['err'])}$ & ${r['neff']:.2f}$ & "
            f"${r['stat3']:.4f}$ \\\\")
    add(r"\midrule")
    add(f"Median & ${med['dll3']:.4f}$ & -- & ${med['sir']:.1f}$ & "
        f"${sci(med['err'])}$ & ${med['neff']:.2f}$ & "
        f"${med['stat3']:.4f}$ \\\\")
    add(r"\bottomrule")
    add(r"\end{tabular}")
    add(r"")
    add(r"\vspace{2pt}")
    add(rf"{{\footnotesize $^{{*}}$ Recovery at the generating order failed for this "
        rf"seed. {n_ok} of {len(rows)} seeds captured $>\!95\%$ of the $M=10$ gain at "
        rf"$M=3$ with a matched map error below $10^{{-2}}$.}}")
    add(r"\end{table}")

    DEST.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {DEST}  ({len(rows)} seeds, {n_ok} recovered)")


if __name__ == "__main__":
    main()
