"""Generate the complete secondary-outcome table (YOR16) from archived estimates.

The manuscript reported the primary MIR endpoint with a figure, a table and an
explicit win count, but summarised remnant pairwise MI and near-dipolarity as
"varied by dataset and comparator" with no numbers anywhere. That asymmetry
reads as selective reporting, and it hides results in both directions: amica is
worse than every comparator on remnant PMI in Table tennis, and better than
every comparator on near-dipolarity in Eyes-open rest.

This writes tab_secondary_outcomes.tex straight from the archived contrast
estimates so the table cannot drift from the data.

Run from figures/src/:  python make_tab_secondary_outcomes.py
"""
from __future__ import annotations

import csv
from pathlib import Path

from _paths import DATA_ROOT as _WORKSPACE, REPO_ROOT, out

_HERE = Path(__file__).resolve().parent
# Was repos/amica-capsule/..., a snapshot of this repository taken while the
# producers lived in the Overleaf clone. The file is carried here and is
# byte-identical, so read the copy in this repository rather than a sibling
# checkout that a collaborator will not have.
SRC = REPO_ROOT / "benchmark/zenodo_figures/estimates_realeeg.csv"
DEST = out("tab_secondary_outcomes.tex")

DATASET_DISPLAY = {
    "ds004505": "Table tennis",
    "ds004504": "Eyes-closed rest",
    "ds004621": "Eyes-open rest",
}
DATASET_ORDER = ["ds004505", "ds004504", "ds004621"]
COMPARATOR_ORDER = ["Picard", "Infomax", "FastICA"]
COMPARATOR_DISPLAY = {"Picard": "Picard", "Infomax": "Extended Infomax",
                      "FastICA": "FastICA"}

# (csv metric, block heading). The direction clause is the point of the table:
# the three metrics do not all run the same way.
METRIC_BLOCKS = [
    ("mir_kbits_s",
     r"Complete MIR (kbits/s) --- \emph{primary, confirmatory}; "
     r"positive favours \texttt{amica}"),
    ("remnant_pmi_percent",
     r"Remnant pairwise MI (percentage points) --- \emph{secondary, "
     r"descriptive}; \textbf{negative} favours \texttt{amica}"),
    ("nd_5_percent",
     r"Near-dipolar fraction, $5\%$ residual variance (percentage points) --- "
     r"\emph{secondary, descriptive}; positive favours \texttt{amica}"),
    ("nd_10_percent",
     r"Near-dipolar fraction, $10\%$ residual variance (percentage points) --- "
     r"\emph{secondary, descriptive}; positive favours \texttt{amica}"),
]


def fmt_p(value: float) -> str:
    """Adjusted p in a form that does not imply more precision than we have."""
    if value >= 0.10:
        return f"{value:.2f}"
    if value >= 0.001:
        return f"{value:.3f}"
    mantissa, exponent = f"{value:.1e}".split("e")
    return rf"${mantissa}{{\times}}10^{{{int(exponent)}}}$"


def fmt_signed(value: float, digits: int = 3) -> str:
    return f"{value:+.{digits}f}"


def main() -> None:
    rows = list(csv.DictReader(SRC.open(encoding="utf-8")))
    index = {(r["dataset"], r["comparator"], r["metric"]): r for r in rows}

    out: list[str] = []
    add = out.append
    add(r"% Generated by figures/src/make_tab_secondary_outcomes.py -- do not hand-edit.")
    add(r"\begin{table}[htbp]")
    add(r"\centering")
    add(r"\caption{")
    add(r"\textbf{Complete real-EEG outcome estimates for every dataset and")
    add(r"comparator.} Paired within-participant differences,")
    add(r"$\Delta = \texttt{amica} - \mathrm{comparator}$, with $95\%$")
    add(r"participant-level bootstrap confidence intervals, standardised paired")
    add(r"effects $d_z$, and the number of participants for whom the difference")
    add(r"favoured \texttt{amica}. \textbf{The three outcomes do not share a")
    add(r"direction convention}: higher complete MIR and higher near-dipolar")
    add(r"fractions favour \texttt{amica}, whereas \emph{lower} remnant pairwise")
    add(r"MI does. Only the nine complete-MIR contrasts were prespecified as")
    add(r"confirmatory; the secondary rows are reported for completeness and")
    add(r"their adjusted $p$-values are descriptive, adjusted within each metric")
    add(r"family. Unadjusted paired-$t$ and Wilcoxon signed-rank values are given")
    add(r"alongside so that the adjustment is visible rather than implicit.")
    add(r"Panels C and D of Figure~\ref{fig:real-eeg-benchmark} plot the")
    add(r"remnant-PMI and near-dipolarity contrasts summarised here.")
    add(r"}")
    add(r"\label{tab:secondary-outcomes}")
    add(r"\scriptsize")
    add(r"\setlength{\tabcolsep}{3.0pt}")
    add(r"\begin{tabular}{llccccc}")
    add(r"\toprule")
    add(r"Dataset & Comparator & $\Delta$ [95\% CI] & $d_z$ [95\% CI] & "
        r"\shortstack{Favouring\\\texttt{amica}, $n/N$} & "
        r"\shortstack{$p$ unadjusted\\$t$; Wilcoxon} & $p_{\mathrm{adj}}$ \\")

    for metric, heading in METRIC_BLOCKS:
        add(r"\midrule")
        add(rf"\multicolumn{{7}}{{l}}{{\emph{{{heading}}}}}\\")
        add(r"\addlinespace[1pt]")
        for dataset in DATASET_ORDER:
            for i, comparator in enumerate(COMPARATOR_ORDER):
                r = index[(dataset, comparator, metric)]
                n = int(r["n"])
                label = (
                    rf"\multirow{{3}}{{*}}{{\shortstack[l]{{{DATASET_DISPLAY[dataset]}\\$n{{=}}{n}$}}}}"
                    if i == 0 else ""
                )
                add(
                    f"{label} & {COMPARATOR_DISPLAY[comparator]} & "
                    f"${fmt_signed(float(r['mean_diff']))}$ "
                    f"[${fmt_signed(float(r['ci_lo']))}$, "
                    f"${fmt_signed(float(r['ci_hi']))}$] & "
                    f"${fmt_signed(float(r['dz']), 2)}$ "
                    f"[${fmt_signed(float(r['dz_lo']), 2)}$, "
                    f"${fmt_signed(float(r['dz_hi']), 2)}$] & "
                    f"${r['favours_amica']}/{n}$ & "
                    f"{fmt_p(float(r['t_p']))}; {fmt_p(float(r['wilcoxon_p']))} & "
                    f"{fmt_p(float(r['holm_p']))} \\\\"
                )
            if dataset != DATASET_ORDER[-1]:
                add(r"\addlinespace[2pt]")

    add(r"\bottomrule")
    add(r"\end{tabular}")
    add(r"\end{table}")

    DEST.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {DEST.resolve()}  ({len(rows)} contrasts)")


if __name__ == "__main__":
    main()
