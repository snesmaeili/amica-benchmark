"""Generate the stopping-status table (YOR15) from the archived run manifests.

The manuscript said the comparators ran under "prespecified stopping rules",
which implies they converged, and separately disclosed that all 25 primary
amica fits hit their iteration cap. Both halves need to be on the page at
once: extended Infomax reached its own (higher) cap in most runs too, while
Picard and FastICA stopped early on essentially every recording. Reporting
one side and not the other is the asymmetry this table removes.

Run from figures/src/:  python make_tab_stopping_status.py
"""
from __future__ import annotations

import csv
import statistics
from pathlib import Path

from _paths import DATA_ROOT as _WS, REPO_ROOT, out

_HERE = Path(__file__).resolve().parent
DEST = out("tab_stopping_status.tex")

RESULTS = {
    # Were repos/amica-capsule/..., a snapshot of this repository taken while
    # the producers lived in the Overleaf clone. All three are carried here and
    # are byte-identical, so read this repository's copies rather than a
    # sibling checkout a collaborator will not have.
    "ds004505": REPO_ROOT / "benchmark/cc_benchmark/results/v3_paper_stage1_cluster/benchmark_results.csv",
    "ds004504": REPO_ROOT / "benchmark/cc_benchmark/results/ds004504_v3/benchmark_results.csv",
    "ds004621": REPO_ROOT / "benchmark/cc_benchmark/results/ds004621_v3/benchmark_results.csv",
}
DATASET_DISPLAY = {
    "ds004505": "Table tennis",
    "ds004504": "Eyes-closed rest",
    "ds004621": "Eyes-open rest",
}

# Rule wording is taken verbatim from the archived convergence-sensitivity
# record so the table cannot describe a criterion the runs did not use.
RULES = {
    "AMICA-Python (JAX-GPU)": (r"\texttt{amica} (JAX-GPU)",
        r"\texttt{min\_dll} with consecutive-increment rule", r"$10^{-9}$"),
    "AMICA-Python (JAX-CPU)": (r"\texttt{amica} (JAX-CPU)",
        r"\texttt{min\_dll} with consecutive-increment rule", r"$10^{-9}$"),
    "AMICA-Python (NumPy-CPU)": (r"\texttt{amica} (NumPy-CPU)",
        r"\texttt{min\_dll} with consecutive-increment rule", r"$10^{-9}$"),
    "Picard": ("Picard", "gradient tolerance", r"$10^{-6}$"),
    "Infomax": ("Extended Infomax",
                "weight change and small-angle criteria", r"$10^{-7}$"),
    "FastICA": ("FastICA", "unmixing convergence tolerance", r"$10^{-6}$"),
}
ORDER = ["AMICA-Python (JAX-GPU)", "AMICA-Python (JAX-CPU)",
         "AMICA-Python (NumPy-CPU)", "Picard", "Infomax", "FastICA"]


def summarise(path: Path) -> dict[str, dict]:
    rows = list(csv.DictReader(path.open(encoding="utf-8")))
    by: dict[str, list[dict]] = {}
    for r in rows:
        by.setdefault(r["method"], []).append(r)
    out = {}
    for method, rs in by.items():
        iters = [int(float(r["n_iter_actual"])) for r in rs
                 if r.get("n_iter_actual") not in (None, "", "nan")]
        caps = {int(float(r["max_iter"])) for r in rs if r.get("max_iter")}
        # converged_before_cap == False means the run stopped because it ran out
        # of iterations, not because the criterion was met.
        at_cap = sum(1 for r in rs
                     if str(r.get("converged_before_cap", "")).lower() in ("false", "0"))
        out[method] = {
            "n": len(rs),
            "median_iter": int(statistics.median(iters)) if iters else None,
            "cap": sorted(caps)[0] if caps else None,
            "at_cap": at_cap,
        }
    return out


def main() -> None:
    data = {ds: summarise(p) for ds, p in RESULTS.items()}

    out: list[str] = []
    add = out.append
    add(r"% Generated by figures/src/make_tab_stopping_status.py -- do not hand-edit.")
    add(r"\begin{table}[htbp]")
    add(r"\centering")
    add(r"\caption{")
    add(r"\textbf{Stopping status for every estimator and dataset.} ``Reached")
    add(r"cap'' counts fits that stopped because the iteration budget was")
    add(r"exhausted rather than because the configured criterion was satisfied.")
    add(r"\texttt{amica} and the comparators were run under different budgets")
    add(r"(3,000 and 5,000 iterations respectively), so the counts describe each")
    add(r"estimator against its own configuration and are not a convergence")
    add(r"ranking. Extended Infomax reached its cap in most runs of every")
    add(r"dataset, whereas Picard and FastICA satisfied their criteria well")
    add(r"before it. Reported decompositions are therefore fixed-budget results")
    add(r"for \texttt{amica} and extended Infomax, and criterion-terminated")
    add(r"results for Picard and FastICA.")
    add(r"}")
    add(r"\label{tab:stopping-status}")
    add(r"\footnotesize")
    add(r"\setlength{\tabcolsep}{2.8pt}")
    add(r"\begin{tabular}{llccc}")
    add(r"\toprule")
    add(r"Method & Stopping criterion (tolerance) & \shortstack{Iteration\\cap} & "
        r"\shortstack{Median completed\\iterations} & \shortstack{Reached cap\\$n/N$} \\")

    for ds in ("ds004505", "ds004504", "ds004621"):
        summary = data[ds]
        n_any = next(iter(summary.values()))["n"]
        add(r"\midrule")
        add(rf"\multicolumn{{5}}{{l}}{{\emph{{{DATASET_DISPLAY[ds]} "
            rf"($N={n_any}$ participants)}}}}\\")
        add(r"\addlinespace[1pt]")
        for method in ORDER:
            if method not in summary:
                continue
            display, rule, tol = RULES[method]
            s = summary[method]
            add(f"{display} & {rule} ({tol}) & ${s['cap']:,}$ & "
                f"${s['median_iter']:,}$ & ${s['at_cap']}/{s['n']}$ \\\\"
                .replace(",", "{,}"))

    add(r"\bottomrule")
    add(r"\end{tabular}")
    add(r"\end{table}")

    DEST.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {DEST}")
    for ds, summary in data.items():
        for m, s in summary.items():
            print(f"  {ds} {m:26} median={s['median_iter']:<6} "
                  f"cap={s['cap']:<6} at_cap={s['at_cap']}/{s['n']}")


if __name__ == "__main__":
    main()
