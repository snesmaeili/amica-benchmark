"""One synthetic-recovery table, recomputed from the archived fits.

This replaces the pair tab_synthetic_recovery_summary (S9, topography and
source correlation, three conditions) and tab_synthetic_full (S10, source
correlation, Amari and MIR, five conditions). They overlapped on the source
correlation for the three shared conditions and *disagreed* on three of those
thirty cells -- all in the AMICA-3k Laplacian column, where S10 read 0.989,
0.149 and 0.157 against the archive's 0.988, 0.139 and 0.159. Neither table was
generated from the archive, so neither could be checked without doing this.

Every number below is recomputed from the per-seed result JSONs, so the two
tables cannot drift apart again. Regime roots follow the mapping already used
by make_main_figures.SINGLE_MODEL_SYNTHETIC_ROOTS.

Run from figures/src/:  python make_tab_synthetic_recovery.py
"""
from __future__ import annotations

import json
import statistics as st
from pathlib import Path

from _paths import DATA_ROOT as _WS, out

_HERE = Path(__file__).resolve().parent
DEST = out("tab_synthetic_recovery.tex")

ROOTS = {
    ("Laplacian", "3k"): "figdata/synth/amica_python_synthetic_v1",
    ("Laplacian", "10k"): "figdata/synth/amica_python_synthetic_v1_lap_amica10k",
    ("Mixture", "3k"): "figdata/synth/amica_python_synthetic_v1_mixed",
    ("Mixture", "10k"): "figdata/synth/amica_python_synthetic_v1_mixed_amica10k",
}
CONDITIONS = [("clean", "clean"), ("noise", "noise"), ("noise_eog", "noise+EOG"),
              ("noise_ecg", "noise+ECG"), ("full", "full")]
# (column label, directory budget key, json top-level key)
COLUMNS = [("AMICA@3k", "3k", "jax_gpu"), ("AMICA@10k", "10k", "jax_gpu"),
           ("Picard", "3k", "picard"), ("Infomax", "3k", "infomax"),
           ("FastICA", "3k", "fastica")]
METRICS = [
    ("r_topo_median", r"Matched topography $|r|$ (higher is better)", 3),
    ("r_source_median", r"Matched-source time-course $|r|$ (higher is better)", 3),
    ("amari_index", r"Amari index (lower is better)", 3),
    ("mir_vs_truth_kbits_s", r"Planted-source MIR, kbits/s (higher is better)", 1),
]


def collect(regime: str, budget: str, jkey: str, cond: str, metric: str) -> list[float]:
    root = _WS / ROOTS[(regime, budget)]
    vals = []
    for p in sorted(root.glob(f"synth_{cond}_seed-*_{jkey}.json")):
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except Exception:
            continue
        gt = d.get(jkey, {}).get("ground_truth", {})
        v = gt.get(metric)
        if v is not None:
            vals.append(float(v))
    return vals


def cell(vals: list[float], digits: int) -> str:
    """Median with interquartile range, or an em-dash when nothing is archived."""
    if not vals:
        return "--"
    med = st.median(vals)
    if len(vals) < 4:
        return f"${med:.{digits}f}$"
    q = st.quantiles(vals, n=4, method="inclusive")
    return f"${med:.{digits}f}$ (${q[2] - q[0]:.{digits}f}$)"


def main() -> None:
    # cell() renders an em-dash for an empty series, so with the synthetic
    # archive absent every cell in the table becomes "--" and only the summary
    # print at the end crashes, on an unrelated-looking StatisticsError. Check
    # the inputs up front and say which ones are missing.
    absent = sorted({rel for rel in ROOTS.values() if not (_WS / rel).is_dir()})
    if absent:
        detail = "\n".join(f"  ! {rel}" for rel in absent)
        raise SystemExit(
            f"refusing to write {DEST.name}: {len(absent)} synthetic archive "
            f"director(ies) missing, which would render every cell as '--'.\n"
            f"{detail}\n"
            "Point AMICA_BENCH_DATA at a tree that has them."
        )

    out: list[str] = []
    add = out.append
    add(r"% Generated by figures/src/make_tab_synthetic_recovery.py -- do not hand-edit.")
    add(r"\begin{table}[htbp]")
    add(r"\centering")
    add(r"\caption{\textbf{Known-source recovery in simulation, ten seeds.} Medians")
    add(r"with interquartile range in parentheses, recomputed from the archived")
    add(r"per-seed fits. \texttt{amica} appears at both iteration caps and the")
    add(r"comparators at their default budgets. The topographic and Amari-distance")
    add(r"rankings agree with each other, but the matched source time-course")
    add(r"correlation is markedly more favourable to the decorrelation-based")
    add(r"estimators once noise is added, and the planted-source MIR does not")
    add(r"separate \texttt{amica} from FastICA. All conditions are reported because")
    add(r"the ordering between methods depends on which property is scored.}")
    add(r"\label{tab:synthetic-recovery}")
    add(r"\scriptsize")
    add(r"\setlength{\tabcolsep}{3.5pt}")
    add(r"\resizebox{\textwidth}{!}{%")
    add(r"\begin{tabular}{llccccc}")
    add(r"\toprule")
    add("Regime & Condition & " + " & ".join(c[0] for c in COLUMNS) + r" \\")

    n_cells = 0
    for mi, (metric, title, digits) in enumerate(METRICS):
        add(r"\midrule")
        add(r"\multicolumn{7}{l}{\emph{" + title + r"}}\\")
        for regime in ("Laplacian", "Mixture"):
            for ckey, clabel in CONDITIONS:
                cells = []
                for _, budget, jkey in COLUMNS:
                    vals = collect(regime, budget, jkey, ckey, metric)
                    n_cells += bool(vals)
                    cells.append(cell(vals, digits))
                add(f"{regime} & {clabel} & " + " & ".join(cells) + r" \\")

    add(r"\bottomrule")
    add(r"\end{tabular}}")
    add(r"\end{table}")

    with open(DEST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {DEST}  ({n_cells} populated cells of "
          f"{len(METRICS) * 2 * len(CONDITIONS) * len(COLUMNS)})")

    # the three cells that used to disagree between S9 and S10
    for cond, was_s9, was_s10 in (("clean", 0.988, 0.989), ("noise", 0.139, 0.149),
                                  ("noise_eog", 0.159, 0.157)):
        v = collect("Laplacian", "3k", "jax_gpu", cond, "r_source_median")
        print(f"  Laplacian/{cond:10} AMICA@3k source |r| = {st.median(v):.3f}  "
              f"(old S9 {was_s9}, old S10 {was_s10})")


if __name__ == "__main__":
    main()
